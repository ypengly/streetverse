import { useGameStore } from '../../store/gameStore';

export function Toasts(): JSX.Element {
  const toasts = useGameStore((s) => s.toasts);
  return (
    <div className="toasts" role="status" aria-live="polite">
      {toasts.map((t) => (
        <div key={t.id} className={`toast ${t.kind}`}>
          {t.text}
        </div>
      ))}
    </div>
  );
}
